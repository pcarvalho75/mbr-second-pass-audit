"""End to end on a small synthetic dataset: every step, the main tables, both figures and the workbook.

The data are generated by tests/synthetic.py; the test checks that the pipeline runs through and that the
accounting identities hold (first pass = retained + lost; final = retained + added). A few minutes.
"""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import pandas as pd

from _paths import REPO
import synthetic

STEPS = [['step_single_cell.py', '--configuration', 'on'], ['step_single_cell.py', '--configuration', 'off'],
         ['step_single_cell.py', '--configuration', 'standard'], ['step_compare_configurations.py'], ['step_pools.py'],
         ['step_pg250.py', '--study', 'primary'], ['step_pg250.py', '--study', 'replication'],
         ['step_within_organism.py', '--organism', 'H'], ['step_posthoc_fc.py'], ['main_tables.py'], ['figure1.py'], ['figure2.py'],
         ['supplementary_data.py']]


class EndToEnd(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.root = Path(cls.temp.name)
        cls.config = synthetic.build(cls.root)
        cls.failed = None
        for step in STEPS:
            result = subprocess.run([sys.executable, str(REPO / 'scripts' / step[0]), *step[1:], '--config', str(cls.config)],
                                    capture_output=True, text=True)
            if result.returncode:
                cls.failed = (step, result.stderr[-3000:])
                break

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def test_every_step_completes(self):
        self.assertIsNone(self.failed)

    def test_single_cell_partition(self):
        for conf in ['on', 'off', 'standard']:
            acc = pd.read_csv(self.root / 'outputs' / 'single-cell' / conf / 'accounting' / 'accounting.tsv', sep='\t')
            self.assertTrue((acc.first_observations == acc.retained_observations + acc.lost_observations).all())
            self.assertTrue((acc.final_observations == acc.retained_observations + acc.second_pass_only_observations).all())
            self.assertTrue((acc.lost_observations == acc.lost_library_present + acc.lost_library_excluded).all())

    def test_pg250_classes_partition(self):
        counts = pd.read_csv(self.root / 'outputs' / 'pg250' / 'primary' / 'export' / 'endpoint_counts.tsv', sep='\t', keep_default_na=False)
        t1 = counts[(counts.endpoint == 'T1') & (counts.scope == 'organism')].set_index(['mask', 'group', 'class']).events
        for mask in ['F1', 'F2', 'F3']:
            for group in 'HYE':
                self.assertEqual(t1[mask, group, 'D'], t1[mask, group, 'R'] + t1[mask, group, 'L'])
                self.assertEqual(t1[mask, group, 'F'], t1[mask, group, 'R'] + t1[mask, group, 'T'])

    def test_outputs_exist(self):
        out = self.root / 'outputs'
        for path in ['tables/tables.md', 'figures/figure1.pdf', 'figures/figure2.pdf', 'figures/figure2-points.tsv', 'supplementary-data.xlsx']:
            self.assertTrue((out / path).exists(), path)


if __name__ == '__main__':
    unittest.main()
